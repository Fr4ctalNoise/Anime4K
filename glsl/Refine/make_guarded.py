"""Build the Detail Guard versions of the Anime4K Mode A chain.

The guard wraps Restore + Upscale together: it saves the untouched frame first, lets
Anime4K run, then at the output size keeps Anime4K on bold line art and flat areas but
shows the original (sharply scaled) wherever there is texture.

mpv's gpu-next renderer keeps textures saved by one shader file private to that file,
so everything must live in one file:

    src/guard_pre.glsl                 (parameters + saves the untouched frame)
    Restore/Anime4K_Restore_CNN_<V>    (copied unchanged)
    Upscale/Anime4K_Upscale_CNN_x2_<V> (copied, internal texture names prefixed)
    src/guard_post.glsl                (texture mask + final blend)

Run from anywhere: python make_guarded.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
GLSL = HERE.parent
VARIANTS = ["S", "M", "L", "VL", "UL"]
HEADER = """// MIT License
// Generated by glsl/Refine/make_guarded.py from {restore} + {upscale}. Do not edit by hand.
//
// Anime4K Mode A (Restore + Upscale x2) with Detail Guard: bold line art and flat areas
// get Anime4K, textured areas (stone, cracks, brushwork) keep the original look.
// Tunables (mpv glsl-shader-opts): guard_strength, texture_threshold, line_threshold,
// guard_debug. guard_strength=0 gives stock Anime4K output.

"""


def main():
    pre = (HERE / "src" / "guard_pre.glsl").read_text()
    post = (HERE / "src" / "guard_post.glsl").read_text()
    for v in VARIANTS:
        restore = GLSL / "Restore" / f"Anime4K_Restore_CNN_{v}.glsl"
        upscale = GLSL / "Upscale" / f"Anime4K_Upscale_CNN_x2_{v}.glsl"
        # Restore and Upscale both name their textures conv2d_*; keep them apart
        up_text = re.sub(r"\bconv2d_", "up_conv2d_", upscale.read_text())
        out = HERE / f"Anime4K_ModeA_{v}_Guarded.glsl"
        header = HEADER.format(restore=restore.name, upscale=upscale.name)
        out.write_text(header + pre + restore.read_text() + up_text + post, newline="\n")
        print(f"wrote {out.name}")


if __name__ == "__main__":
    main()
